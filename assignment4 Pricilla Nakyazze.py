# Create a class called BankAccount that has four attributes: bankname, firstname, lastname, and balance default set to zero
class BankAccount:
    def __init__(self, bankname, firstname, lastname, balance=0):
        self.bankname = bankname
        self.firstname = firstname
        self.lastname = lastname
        self.balance = balance
# deposit() that allows the user to make deposits into their balance.
    def deposit(self):
        amount = float(input("Enter deposit amount: $"))
        if amount > 0:
            self.balance += amount
            print(f"Deposited ${amount:.2f}. New balance: ${self.balance:.2f}")
        else:
            print("Deposit amount must be greater than zero.")
# withdrawal() that allows the user to withdraw from their balance
    def withdrawal(self):
        amount = float(input("Enter withdrawal amount: $"))
# Withdrawal may not exceed the available balance. consider a conditional argument in your withdrawal() method. If amount is greater than balance.
        if amount > self.balance:
            print(f"Declined: Withdrawal of ${amount:.2f} exceeds available balance (${self.balance:.2f}).")
        elif amount <= 0:
            print("Withdrawal amount must be greater than zero.")
        else:
            self.balance -= amount
            print(f"Withdrew ${amount:.2f}. Remaining balance: ${self.balance:.2f}")
# the str() method in order to display the bank name, owner name, and current balance
    def __str__(self):
        return f"Bank: {self.bankname} | Owner: {self.firstname} {self.lastname} | Balance: ${self.balance:.2f}"


