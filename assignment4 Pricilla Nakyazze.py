import math

class Box:
  def __init__(self, length, width):
        self.length = length
        self.width = width
 # render() that prints out to the screen a box made with asterisks of length and width dimensions
  def render(self):
       for _ in range(self.width):
        print("*" * self.length)



#● A method called invert() that switches length and width with each other
  def invert(self):
        """Swaps length and width."""
        self.length, self.width = self.width, self.length
# Methods get_area() and get_perimeter() that return appropriate geometric calculations
  def get_area(self):
        """Returns the area of the box."""
        return self.length * self.width

  def get_perimeter(self):
        """Returns the perimeter of the box."""
        return 2 * (self.length + self.width)
#A method called double() that doubles the size of the box. Hint: Pay attention to return value here.
  def double(self):
        """Doubles both length and width."""
        self.length *= 2
        self.width *= 2
#Implement __eq__ so that two boxes can be compared using ==. Two boxes are equal if their respective lengths and widths are identical.
  def __eq__(self, other):
        """Checks if two boxes have identical length and width."""
        if isinstance(other, Box):
            return self.length == other.length and self.width == other.width
        return False
#A method print_dim() that prints to screen the length and width details of the box
  def print_dim(self):
        """Prints the length and width dimensions."""
        print(f"Length: {self.length}, Width: {self.width}")
# A method get_dim() that returns a tuple containing the length and width of the box
  def get_dim(self):
        """Returns the dimensions as a tuple (length, width)."""
        return (self.length, self.width)
#A method combine() that takes another box as an argument and increases the length and width by the dimensions of the box passed in
  def combine(self, other):
        """Adds dimensions of another box to this box."""
        if isinstance(other, Box):
            self.length += other.length
            self.width += other.width
#A method get_hypot() that finds the length of the diagonal that cuts through the middle
  def get_hypot(self):
        """Calculates and returns the diagonal / hypotenuse."""
        return math.hypot(self.length, self.width)

